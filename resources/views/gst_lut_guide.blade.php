                    <h2 class="fw-bold text-dark mb-3">1. What is a Letter of Undertaking (LUT)?</h2>
                    <p class="text-secondary leading-relaxed">
                        Under Section 16 of the Integrated Goods and Services Tax (IGST) Act, 2017, the export of goods or services outside India is treated as a <strong>"Zero-Rated Supply"</strong>. Indian exporters have two legal routes to fulfill export tax obligations:
                    </p>
                    <ol class="text-secondary leading-relaxed mb-4">
                        <li><strong>Export with payment of IGST:</strong> Pay 18% IGST upfront from working capital, then apply for a tax refund from the GST department (which can take 60–120 days).</li>
                        <li><strong>Export under Letter of Undertaking (LUT) without payment of IGST:</strong> File Form GST RFD-11 annually on the GST portal to export at 0% tax upfront with zero cash blockage.</li>
                    </ol>

                    <div class="callout-box">
                        <h5 class="fw-bold text-primary mb-2">💡 Why Exporters Choose the LUT Route</h5>
                        <p class="mb-0 text-dark fs-7">Filing an LUT completely prevents liquidity entrapment. You do not have to deposit 18% on your high-value foreign billing, safeguarding working capital and eliminating long refund processing queues.</p>
                    </div>

                    <h2 class="fw-bold text-dark mt-5 mb-3">2. Who is Eligible to File Form GST RFD-11?</h2>
                    <p class="text-secondary leading-relaxed">
                        Any registered taxpayer in India who exports goods or services is eligible, provided:
                    </p>
                    <ul class="text-secondary leading-relaxed mb-4">
                        <li>They possess an active GSTIN registration.</li>
                        <li>They have not been prosecuted for any tax evasion offense exceeding ₹250 Lakhs under the CGST/IGST Act.</li>
                        <li>The LUT is filed prior to the dispatch of goods or the issuance of service invoices for each financial year (April 1 to March 31).</li>
                    </ul>

                    <h2 class="fw-bold text-dark mt-5 mb-3">3. Step-by-Step Procedure to File LUT on the GST Portal</h2>
                    <div class="p-3 bg-light rounded-3 border mb-4">
                        <ol class="mb-0 text-secondary fs-7 d-flex flex-column gap-2">
                            <li>Log in to the official <strong>GST Portal</strong> (gst.gov.in) with your credentials.</li>
                            <li>Navigate to <code>Services > User Services > Furnish Letter of Undertaking (LUT)</code>.</li>
                            <li>Select the applicable Financial Year (e.g., 2026–2027).</li>
                            <li>If filing for the first time, upload details of two independent witnesses (Name, Occupation, Address).</li>
                            <li>Sign the declaration digitally using <strong>DSC</strong> (for Companies/LLPs) or <strong>EVC OTP</strong> (for Sole Proprietors).</li>
                            <li>Download the generated <strong>Acknowledgment Receipt Note (ARN)</strong>. The ARN is instantly generated and valid for the entire financial year.</li>
                        </ol>
                    </div>

                    <h2 class="fw-bold text-dark mt-5 mb-3">4. Mandatory Invoice Text & Declarations</h2>
                    <p class="text-secondary leading-relaxed">
                        As per Rule 96A of the CGST Rules, every export invoice issued under an LUT must carry a specific statutory endorsement:
                    </p>
                    <div class="p-3 bg-dark text-white rounded-3 font-mono fs-8 mb-4">
                        "SUPPLY MEANT FOR EXPORT UNDER LETTER OF UNDERTAKING WITHOUT PAYMENT OF INTEGRATED TAX"
                    </div>
                    <p class="text-secondary leading-relaxed">
                        Additionally, you must print:
                    </p>
                    <ul class="text-secondary leading-relaxed mb-4">
                        <li>Your LUT ARN number (e.g., <code>AD270326001928K</code>) and Date of Filing.</li>
                        <li>Client's full foreign address and recipient country.</li>
                        <li>Applicable SAC (Services Accounting Code) or HSN Code.</li>
                        <li>Billed currency, foreign exchange conversion rate, and equivalent INR value.</li>
                    </ul>

