                <h2 class="h3 fw-bold mt-5 mb-3">4. Accounting for Forex Fluctuations under ICAI AS-11</h2>
                <p>
                    When preparing financial statements in India, compliance with <strong>Accounting Standard 11 (AS-11)</strong> issued by the <a href="https://www.icai.org/" target="_blank" rel="noopener" class="text-primary fw-medium">Institute of Chartered Accountants of India (ICAI)</a> is mandatory for recording foreign currency transactions.
                </p>
                <div class="p-4 rounded-4 mb-4" style="background:#f1f5f9; border-left: 4px solid #0f172a;">
                    <h5 class="fw-bold text-dark mb-2">The Two-Step Accounting Standard Rule:</h5>
                    <ol class="fs-7 text-muted mb-0">
                        <li><strong>Initial Recognition (Invoice Date):</strong> A foreign currency transaction must be recorded in Indian Rupees by applying the exchange rate between the reporting currency and the foreign currency at the date of the transaction (or the notified CBIC Customs benchmark rate for the month).</li>
                        <li><strong>Settlement Date (Realization Date):</strong> Exchange differences arising on the settlement of monetary items must be recognized as income or expense in the period in which they arise.</li>
                    </ol>
                </div>

                <div class="formula-card">
