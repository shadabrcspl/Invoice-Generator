                <h2 class="h3 fw-bold mt-5 mb-3">2. The Mathematics: Interbank Rate vs. TT Buying Rate</h2>
                <p>
                    To understand where your revenue evaporates, you must distinguish between the three primary exchange rates in international banking:
                </p>
                <ol class="fs-7 text-slate-700">
                    <li><strong>Interbank Rate (Mid-Market Rate / IBR):</strong> The true wholesale rate at which global banks trade currencies amongst themselves (the rate shown on Google, Bloomberg, and XE).</li>
                    <li><strong>TT Buying Rate (Telegraphic Transfer Buying):</strong> The commercial rate applied by an Indian bank when buying foreign currency from you and crediting Indian Rupees to your account.</li>
                    <li><strong>Bank Spread:</strong> The difference between the Interbank Rate and the TT Buying Rate:
                        <div class="formula-card my-2">
                            Spread (INR) = Interbank Reference Rate - Applied TT Buying Rate<br>
                            Forex Leakage (INR) = Invoiced Amount (Forex) × Spread (INR)
                        </div>
                    </li>
                </ol>

