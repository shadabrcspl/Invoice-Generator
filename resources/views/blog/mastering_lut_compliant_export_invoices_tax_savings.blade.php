                    <div class="col-md-4">
                        <div class="p-3 border rounded-3 bg-white h-100 shadow-2xs">
                            <span class="badge bg-primary text-white mb-2">Criterion 3</span>
                            <h6 class="fw-bold mb-1">Place of Supply</h6>
                            <p class="fs-8 text-muted mb-0">The place of supply of service must be outside India as determined by Section 13 of the IGST Act (general rule: location of recipient).</p>
