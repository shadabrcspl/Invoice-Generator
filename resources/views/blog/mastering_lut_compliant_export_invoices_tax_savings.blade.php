                <h2 class="h3 fw-bold mt-5 mb-3">2. Statutory Framework: Section 16 & Rule 96A</h2>
                <p>
                    To withstand GST audits and department summons, you must understand the primary provisions governing zero-rated service exports:
                </p>
                <div class="row g-3 my-3">
                    <div class="col-md-6">
                        <div class="p-3 border rounded-3 bg-light h-100">
                            <h6 class="fw-bold text-dark mb-1">Section 16 of the IGST Act, 2017</h6>
                            <p class="fs-7 text-muted mb-0">
                                Formally categorizes the export of goods or services as a <strong>"Zero-Rated Supply"</strong>. Subsection (3) provides the legal right to export without payment of integrated tax upon furnishing a Letter of Undertaking in accordance with the prescribed rules.
                            </p>
                        </div>
                    </div>
                    <div class="col-md-6">
                        <div class="p-3 border rounded-3 bg-light h-100">
                            <h6 class="fw-bold text-dark mb-1">Rule 96A of the CGST Rules, 2017</h6>
                            <p class="fs-7 text-muted mb-0">
                                Specifies the conditions of the LUT. Under Rule 96A(1)(b), the exporter undertakes to realize the full export proceeds in convertible foreign exchange within <strong>1 year</strong> from the date of the export invoice (or within the period allowed by RBI under FEMA).
                            </p>
                        </div>
                    </div>
                </div>

                <div class="callout-legal">
                    <h6 class="fw-bold text-dark mb-1">⚠️ Crucial Statutory Obligation: The 1-Year Realization Rule</h6>
                    <p class="fs-7 mb-0">
                        If an exporter fails to receive convertible foreign exchange within the period prescribed by the Reserve Bank of India (typically 9 months under Regulation 9 of FEMA 23R, or within 15 days past the one-year window under Rule 96A), the exporter must deposit the unpaid 18% IGST along with interest under Section 50 within 15 days. Tracking inward remittances with Purpose Code <code>P0802</code> and obtaining e-FIRCs is therefore non-negotiable.
                    </p>
                </div>
