                    One of the greatest benefits of the zero-rated LUT regime is that your entitlement to <strong>Input Tax Credit (ITC)</strong> is 100% protected. When you purchase computers, pay office rent, or purchase SaaS tools (Google Workspace, GitHub, Figma, AWS) subject to domestic 18% GST:
                </p>
                <ol class="fs-7 text-slate-700">
                    <li>Your input GST accumulates safely in your <strong>Electronic Credit Ledger</strong>.</li>
                    <li>Because your export sales are taxed at 0% under LUT, you have no domestic output tax liability to offset.</li>
                    <li>Under Section 54(3) of the CGST Act read with Rule 89(4), you can file a refund claim for <strong>Accumulated Unutilized Input Tax Credit</strong> and receive the cash deposited directly into your bank account.</li>
                </ol>
            </section>

