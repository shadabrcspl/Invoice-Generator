            <!-- Section 6: Realization Timelines & Penalties -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">6. Statutory Realization Timelines & Non-Compliance Penalties</h2>
                <p>
                    Under Rule 96A(1)(b) of the CGST Rules read with the Foreign Exchange Management (Export of Goods and Services) Regulations 2015, foreign convertible exchange must be received in India within:
                </p>
                <div class="p-3 bg-white border rounded-3 mb-3">
                    <strong>Statutory Realization Deadline:</strong> Exactly <strong>9 months</strong> from the date of issuance of the export invoice (or within such further period as may be allowed by the Commissioner / RBI upon formal application).
                </div>
                <p>
                    If the export payment is not realized within 15 days after the expiry of the 9-month window, the exporter is legally bound to deposit the integrated tax (18% IGST) along with <strong>18% per annum interest</strong> calculated from the original invoice due date under Section 50(1). Once the proceeds are realized in foreign exchange subsequently, the taxpayer may claim a refund of the tax paid, but the 18% interest component is non-refundable.
                </p>
            </section>

