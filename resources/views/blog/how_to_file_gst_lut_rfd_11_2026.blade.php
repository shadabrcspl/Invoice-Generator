            <div class="callout-box">
                <h4 class="h6 fw-bold text-primary text-uppercase mb-2">Executive Summary</h4>
                <p class="mb-0 text-slate-700">
                    If you export software, IT services, digital consulting, or goods from India, filing a <strong>Letter of Undertaking (LUT) in Form GST RFD-11</strong> allows you to supply zero-rated services without paying 18% Integrated Goods and Services Tax (IGST) upfront. This statutory declaration prevents working capital blockage and eliminates the slow bureaucratic process of applying for government tax refunds.
                </p>
