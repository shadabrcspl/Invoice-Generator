            <!-- Section 1: Statutory Legal Framework -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">1. Statutory Framework: Rule 96A of CGST Rules & Section 16 IGST Act</h2>
                <p>
                    Under <strong>Section 16(1) of the Integrated Goods and Services Tax (IGST) Act, 2017</strong>, the export of goods or services is treated as a "zero-rated supply." Exporters are provided two distinct routes to execute zero-rated exports:
                </p>
                <ul>
                    <li><strong>Route 1: Export under LUT or Bond without payment of IGST (Rule 96A):</strong> You supply services at 0% tax, quote your LUT Application Reference Number (ARN) on every invoice, and preserve all your working capital.</li>
                    <li><strong>Route 2: Export with payment of IGST and claim refund (Rule 96):</strong> You pay 18% tax from your electronic cash or credit ledger when filing GSTR-3B and subsequently claim a cash refund from the GST department.</li>
                </ul>
                <p>
                    For IT contractors, freelance software engineers, and digital marketing agencies, <strong>Route 1 (LUT)</strong> is universally preferred because paying 18% cash tax on foreign billings creates massive cash flow strain while waiting 60 to 120 days for refund disbursements.
                </p>
            </section>

            <!-- Section 2: Eligibility Criteria -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">2. Who is Eligible to File an LUT vs Who Must Furnish a Bond?</h2>
                <p>
                    Under Notification No. 37/2017-Central Tax, any registered taxpayer exporting goods or services is eligible to file a Letter of Undertaking instead of a physical bond, provided they meet one straightforward condition:
                </p>
                <div class="p-3 bg-white border rounded-3 mb-3">
                    <strong class="text-danger">Disqualification Rule:</strong> A registered person is <em>not eligible</em> to furnish an LUT if they have been prosecuted for any offence under the Central Goods and Services Tax Act, 2017 or the Integrated Goods and Services Tax Act, 2017, where the amount of tax evaded exceeds <strong>₹250 Lakhs (₹2.5 Crore)</strong>.
                </div>
                <p>
                    If an exporter has been prosecuted for tax evasion exceeding ₹2.5 Crore, they must furnish an <strong>Export Bond on non-judicial stamp paper</strong> backed by a bank guarantee for 15% of the estimated tax liability. All other registered businesses and professionals are legally entitled to furnish an online LUT free of cost in minutes.
                </p>
            </section>

            <!-- Section 3: Step-by-Step Portal Walkthrough -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">3. Step-by-Step Portal Walkthrough: Furnishing Form GST RFD-11</h2>
                <p>
                    Filing the LUT is completely paperless and executed directly on the official GST Common Portal (<a href="https://www.gst.gov.in" target="_blank" rel="noopener">gst.gov.in</a>). Follow these exact steps:
                </p>

                <!-- Step 1 -->
                <div class="step-card d-flex align-items-start">
                    <div class="step-number">1</div>
                    <div>
                        <h3 class="h5 fw-bold mb-2">Log in and Navigate to User Services</h3>
                        <p class="text-slate-600 mb-0">
                            Log in to the GST Portal using your username, password, and captcha. On the top navigation bar, go to <strong>Services → User Services → Furnish Letter of Undertaking (LUT)</strong>.
                        </p>
                    </div>
                </div>

                <!-- Step 2 -->
                <div class="step-card d-flex align-items-start">
                    <div class="step-number">2</div>
                    <div>
                        <h3 class="h5 fw-bold mb-2">Select the Applicable Financial Year</h3>
                        <p class="text-slate-600 mb-0">
                            In the dropdown menu labelled <strong>"LUT Applied for Financial Year"</strong>, select the relevant fiscal cycle (e.g., <strong>2026-2027</strong>). Note: LUT filings become active on April 1st and expire automatically on March 31st of the following calendar year.
                        </p>
                    </div>
                </div>

                <!-- Step 3 -->
                <div class="step-card d-flex align-items-start">
                    <div class="step-number">3</div>
                    <div>
                        <h3 class="h5 fw-bold mb-2">Review Previous LUT Reference (If Applicable)</h3>
                        <p class="text-slate-600 mb-0">
                            If you furnished an LUT in the preceding financial year, the portal will allow you to enter the previous ARN. You may also upload an optional PDF copy of the previous year's acknowledgment. If this is your first export year, you can proceed directly.
                        </p>
                    </div>
                </div>

                <!-- Step 4 -->
                <div class="step-card d-flex align-items-start">
                    <div class="step-number">4</div>
                    <div>
                        <h3 class="h5 fw-bold mb-2">Accept the Three Statutory Undertakings</h3>
                        <p class="text-slate-600 mb-2">
                            You must check all three statutory declaration boxes under Form RFD-11:
                        </p>
                        <ol class="small text-slate-600 ps-3 mb-0">
                            <li>To export the goods/services within the time period specified in sub-rule (1) of Rule 96A.</li>
                            <li>To observe all the provisions of the GST Act and the rules made thereunder in respect of export of goods or services.</li>
                            <li>To pay the integrated tax liable in respect of the goods/services along with interest at 18% per annum in case of failure to export or realize proceeds.</li>
                        </ol>
                    </div>
                </div>

                <!-- Step 5 -->
                <div class="step-card d-flex align-items-start">
                    <div class="step-number">5</div>
                    <div>
                        <h3 class="h5 fw-bold mb-2">Enter Details of Two Independent Witnesses</h3>
                        <p class="text-slate-600 mb-0">
                            The portal requires full names, occupations, and residential/business addresses of two independent witnesses. These can be employees, business associates, colleagues, or family members of legal age who reside in India.
                        </p>
                    </div>
                </div>

                <!-- Step 6 -->
                <div class="step-card d-flex align-items-start">
                    <div class="step-number">6</div>
                    <div>
                        <h3 class="h5 fw-bold mb-2">Sign and Submit via DSC or EVC</h3>
                        <p class="text-slate-600 mb-0">
                            Select the Primary Authorized Signatory from the dropdown and enter the Place of submission. Sole proprietorships and partnerships can verify via <strong>EVC (Electronic Verification Code)</strong> received on the registered mobile number and email. Companies and LLPs must authenticate via a registered <strong>Digital Signature Certificate (DSC Class 3)</strong>.
                        </p>
                    </div>
                </div>

            </section>

            <!-- Section 4: ARN & Download -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">4. Downloading Your Official LUT Acknowledgment PDF</h2>
                <p>
                    Upon successful electronic verification, the portal immediately generates an <strong>Application Reference Number (ARN)</strong>. The system status will update to "Submitted" and "Approved" instantaneously.
                </p>
                <p>
                    To download the official PDF for your banking records, go to <strong>Services → User Services → View My Submitted Applications</strong>. Select "Letter of Undertaking (LUT)" as the Application Type, locate your submission, and download the signed PDF. Store this document safely; your Authorized Dealer (AD) bank will require it to clear foreign inward remittances and issue Foreign Inward Remittance Certificates (FIRC).
                </p>
            </section>

            <!-- Section 5: Mandatory Invoice Endorsements -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">5. Mandatory Endorsement Text Required on Export Invoices</h2>
                <p>
                    Filing the LUT is only half the compliance battle. To maintain legal validity under Rule 46 of the CGST Rules, every commercial or tax invoice sent to an international client must bear the following exact statutory text:
                </p>

                <div class="endorsement-code-box">
                    SUPPLY MEANT FOR EXPORT OF SERVICES UNDER LETTER OF UNDERTAKING WITHOUT PAYMENT OF INTEGRATED TAX
                </div>

                <p>
                    In addition to this statement, your invoice header or regulatory block must explicitly declare:
                </p>
                <ul>
                    <li>Your 15-digit GSTIN</li>
                    <li>The RFD-11 Application Reference Number (ARN)</li>
                    <li>The Financial Year of validity (e.g., FY 2026-27)</li>
                    <li>Place of Supply explicitly marked as "Outside India"</li>
                    <li>Services Accounting Code (SAC) such as 998311 or 998312</li>
                </ul>
                <div class="callout-box bg-white border">
