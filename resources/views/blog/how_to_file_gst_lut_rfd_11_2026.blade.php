            <!-- Section 8: Common Portal Errors and Solutions -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">8. Five Common GST RFD-11 Portal Errors & How to Fix Them</h2>
                <div class="d-flex flex-column gap-3">
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-dark mb-1">Error 1: "DSC Signer Name Mismatch"</h4>
                        <p class="small text-slate-600 mb-0">
                            <strong>Cause & Fix:</strong> The PAN embedded inside your Class 3 Digital Signature Certificate must match the PAN of the Primary Authorized Signatory listed on the GST registration portal. Update the authorized signatory in your core registration amendment first if your director or partner has changed.
                        </p>
                    </div>
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-dark mb-1">Error 2: "Witness Address Incomplete or Special Characters"</h4>
                        <p class="small text-slate-600 mb-0">
                            <strong>Cause & Fix:</strong> The portal form rejects symbols like `#`, `/`, or `@` in witness address fields. Enter plain alphanumeric text and ensure the PIN code and state match official postal databases.
                        </p>
                    </div>
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-dark mb-1">Error 3: "Financial Year Already Submitted"</h4>
                        <p class="small text-slate-600 mb-0">
                            <strong>Cause & Fix:</strong> The portal only permits one active LUT per GSTIN per financial year. Check your "View Submitted Applications" to confirm your existing ARN before attempting a duplicate submission.
                        </p>
                    </div>
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-dark mb-1">Error 4: "ARN Not Reflecting in GSTR-1 Table 6A"</h4>
                        <p class="small text-slate-600 mb-0">
                            <strong>Cause & Fix:</strong> In GSTR-1 Table 6A, select "Zero Rated Supply without payment of tax" and enter the 15-character ARN. It can take up to 2 hours for newly approved ARNs to propagate across all portal filing modules.
                        </p>
                    </div>
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-dark mb-1">Error 5: "Session Timeout During EVC OTP Verification"</h4>
                        <p class="small text-slate-600 mb-0">
                            <strong>Cause & Fix:</strong> Clear your browser cache or open the portal in an Incognito window. GST portal OTPs expire in 10 minutes, but portal sessions time out after 15 minutes of idle time.
                        </p>
                    </div>
                </div>
