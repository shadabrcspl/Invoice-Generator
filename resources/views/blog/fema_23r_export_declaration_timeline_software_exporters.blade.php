                    <li><strong>Invoice Issued:</strong> October 15, 2026 (Invoice <code>INV-202610-0010</code>, AED 950.00).</li>
                    <li><strong>Month-End Anchor Date:</strong> October 31, 2026.</li>
                    <li><strong>Statutory EDF Submission Deadline:</strong> <strong>November 30, 2026</strong> (30 days from month-end).</li>
                    <li><strong>Status:</strong> You have until November 30 to submit the EDF Cum Request Letter to HDFC Bank.</li>
                </ul>
            </div>

