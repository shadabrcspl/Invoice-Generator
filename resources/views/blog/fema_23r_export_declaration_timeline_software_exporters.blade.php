                </ul>
            </div>

            <h2 class="h3 fw-bold mt-5 mb-3">Handling Advance Inward Remittances</h2>
            <p>
                One of the most frequent friction points for software freelancers and digital agencies is receiving upfront retainers or milestones before service delivery:
            </p>

            <div class="callout-warning">
                <h6 class="fw-bold text-dark mb-1">Step 1: Immediate Fund Application</h6>
                <p class="fs-7 mb-2">
                    When the overseas client sends an advance via wire transfer, submit a basic **Disposal Instruction** to HDFC Bank quoting Purpose Code <code>P0802</code>. HDFC will convert the foreign exchange and credit your current account immediately.
                </p>
                <h6 class="fw-bold text-dark mb-1">Step 2: Subsequent EDF Lodgement</h6>
                <p class="fs-7 mb-0">
                    Once the milestone is completed and the commercial tax invoice is generated, compile the **Export Declaration Form (EDF)** quoting the earlier remittance reference, and submit it within 30 days of the invoice month-end.
                </p>
            </div>

            <h2 class="h3 fw-bold mt-5 mb-3">What Happens During EDPMS Regularisation?</h2>
            <p>
                Every foreign invoice and inward wire transfer creates two electronic entries in the banking network:
            </p>
            <ol class="fs-7 text-slate-700">
                <li><strong>The Inward Remittance Entry (IRM / NOSTRO Credit):</strong> Created when foreign currency enters India.</li>
                <li><strong>The Export Declaration Form Entry (EDF Bill):</strong> Created when your AD bank lodges your declaration form.</li>
            </ol>
            <p>
                When HDFC Bank’s trade desk verifies your EDF against the remittance advice, they perform **Bill Regularisation in EDPMS**. This zeroes out the open export obligation on RBI’s servers.
            </p>

            <div class="callout-box">
                <h6 class="fw-bold text-dark mb-1">⚠️ Danger of Non-Regularisation: The RBI Caution List</h6>
                <p class="fs-7 mb-0">
                    If an exporter fails to regularise service export bills within the realization period (typically 9 months from the date of export under Regulation 9 of FEMA 23R), the entity is automatically flagged on the **RBI Caution List / EXIM Warning Database**. Once flagged:
                    <br>• Banks cannot process trade credit without prior RBI approval.
                    <br>• Future inward remittances are subject to stringent forensic scrutiny.
                    <br>• Zero-rated GST refunds and export benefits may be withheld by tax authorities.
                </p>
            </div>

