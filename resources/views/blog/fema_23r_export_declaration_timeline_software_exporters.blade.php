            <h2 class="h3 fw-bold mt-5 mb-3">Understanding the Shift from Goods to Services in FEMA 23(R)</h2>
            <p>
                Historically, the Reserve Bank of India’s export declaration frameworks focused almost exclusively on physical merchandise tracked by Customs through Shipping Bills on the ICEGATE network. Intangible software, consulting, and SaaS exports delivered over the internet were governed by broad SOFTEX rules or bank-level self-certifications.
            </p>
            <p>
                Effective <strong>October 01, 2026</strong>, the revised **Foreign Exchange Management (Export and Import of Goods and Services) Regulations, 2026 (FEMA 23R)** formally brought cross-border service exports into a synchronized electronic surveillance mechanism managed through the **EDPMS (Export Data Processing and Monitoring System)**.
            </p>

            <h2 class="h3 fw-bold mt-5 mb-3">How the 30-Day Rule Works in Practice</h2>
            <p>
                The 30-day timeline is calculated not from the invoice date itself, but from the **last day of the calendar month** in which the invoice was generated:
            </p>

            <div class="timeline-card">
                <div class="d-flex justify-content-between align-items-center mb-2">
