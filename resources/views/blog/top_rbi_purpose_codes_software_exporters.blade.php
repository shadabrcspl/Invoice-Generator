                <h2 class="h3 fw-bold mb-3">6. How to Instruct Clients, PayPal, Stripe, and Wise</h2>
                <p>
                    Prevention is vastly simpler than amending a settled bank wire. Follow these best practices:
                </p>
                <ul>
                    <li><strong>On Your Invoices:</strong> Explicitly print the required RBI Purpose Code directly on your invoice under the banking instructions block:
                        <div class="p-2 bg-slate-100 rounded text-slate-800 font-mono small my-2">
                            Mandatory Wire Instructions for Remitter: Please quote RBI Purpose Code [P0802 - Software Implementation] and Invoice Reference [#INV-2026-0042] in Field 70 (Remittance Information) of your SWIFT transfer.
                        </div>
                    </li>
                    <li><strong>On Wise / Payoneer:</strong> Set your default business receiving purpose inside your profile settings to "Computer and Information Services (P0802)."</li>
                    <li><strong>On Stripe / PayPal India:</strong> Complete your mandatory KYC profile and select "Computer and Information Services (P0802)" or "Consultancy (P1006)" so automated nodal bank transfers carry the accurate tag.</li>
                </ul>
            </section>

            <!-- Section 7: Correcting a Wrong Purpose Code -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">7. How to Correct a Wrong Purpose Code with Your Bank</h2>
                <p>
                    If your bank has already credited funds under an erroneous purpose code, you can initiate a formal <strong>Purpose Code Amendment Request</strong>:
                </p>
                <ol class="small text-slate-700">
                    <li>Draft an official request letter on your company letterhead addressed to the Branch Manager / Forex Inward Remittance Desk of your AD Bank.</li>
                    <li>Specify the transaction details: Foreign Inward Reference (FIRC/FIRS No.), Date of Credit, Amount in Foreign Currency, Amount in INR, Existing Erroneous Purpose Code, and Requested Correct Code.</li>
                    <li>Attach supporting documents: Certified copy of the commercial invoice, Client Statement of Work (SOW) or contract, FEMA 23(R) self-declaration, and copy of the SWIFT MT103 message.</li>
                    <li>The bank forex desk will verify the documentation, amend the record in their internal core banking system (CBS), and update the EDPMS/DGFT IRM feed.</li>
                </ol>
            </section>

