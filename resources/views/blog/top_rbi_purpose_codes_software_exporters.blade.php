            <!-- Section 1: What are RBI Purpose Codes? -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">1. What are RBI Purpose Codes and Why Do They Exist?</h2>
                <p>
                    Under the <strong>Foreign Exchange Management Act (FEMA), 1999</strong>, the Reserve Bank of India tracks every cross-border inflow and outflow to classify the country’s Balance of Payments (BoP) and ensure compliance with foreign exchange regulations.
                </p>
                <p>
                    Every purpose code is an alphanumeric string starting with the letter <strong>'P' for inward remittances (Receipts)</strong> and <strong>'S' for outward remittances (Payments)</strong>. The subsequent digits classify the exact economic nature of the transaction—such as computer software, advertising, royalties, or travel.
                </p>
                <p>
                    For Indian IT exporters, Authorised Dealer Category-I (AD Category-I) banks are strictly required by the RBI Master Direction on Reporting under FEMA to transmit this purpose code into the <strong>Export Data Processing and Monitoring System (EDPMS)</strong> and the DGFT electronic Inward Remittance Message (IRM) system.
                </p>
            </section>

