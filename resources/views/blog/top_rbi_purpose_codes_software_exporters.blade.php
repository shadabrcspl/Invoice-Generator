            <!-- Section 4: How Inward Remittance Clearance Works -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">4. How Foreign Inward Remittance Clearance Works</h2>
                <p>
                    When an overseas client initiates a cross-border wire (such as a SWIFT MT103 credit), the transaction passes through intermediate correspondent banks before arriving at your Authorised Dealer (AD) bank in India:
                </p>
                <ol>
                    <li><strong>Inward Wire Notification:</strong> Your bank receives the foreign currency credit into their overseas Nostro account and alerts your branch.</li>
                    <li><strong>Inward Remittance Disposal Request (IRDR):</strong> The bank holds the funds in suspense and requests the beneficiary to provide an IRDR form (or digital disposal request via net banking) specifying the Purpose Code, contract description, and invoice number.</li>
                    <li><strong>FEMA 23(R) SoftEX Declaration:</strong> For software services without physical customs shipping bills, banks require a standard FEMA 23(R) self-declaration certifying that the service does not attract physical customs clearance.</li>
                    <li><strong>Currency Liquidation:</strong> Once validated, the bank converts the USD/EUR/GBP to INR using the Card rate or agreed TT Buying rate, credits your current account, and emits an electronic IRM message.</li>
                </ol>
            </section>

            <!-- Section 5: Common Traps and Why Banks Reject FIRCs -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">5. Common Traps That Trigger RBI Inquiries and FIRC Rejections</h2>
                <div class="d-flex flex-column gap-3">
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-danger mb-1">Trap 1: The Client Selects "Family Maintenance / Gift" (P0000 / P1301)</h4>
                        <p class="small text-slate-600 mb-0">
                            When international clients use consumer transfer apps (like Wise personal or Remitly), they often casually pick "gift to friend" or "personal expenses." Indian banks classify this as personal non-business remittance. <strong>Consequence:</strong> You cannot generate an e-BRC on DGFT, your GST auditor will reject it for 0% zero-rated LUT export, and you may be assessed 18% IGST plus penalties.
                        </p>
                    </div>
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-danger mb-1">Trap 2: Catch-All Miscellaneous Purpose Codes (P1099)</h4>
                        <p class="small text-slate-600 mb-0">
                            Selecting "Other business services not included elsewhere" (P1099) invites heightened scrutiny from the RBI’s foreign exchange monitoring cell. Always use specific IT codes (P0802, P0803) or Consulting codes (P1006).
                        </p>
                    </div>
                    <div class="p-3 bg-white border rounded-3">
                        <h4 class="h6 fw-bold text-danger mb-1">Trap 3: Inward Wire Name Mismatch</h4>
                        <p class="small text-slate-600 mb-0">
                            If your export invoice is billed to "Acme Corp US," but the payment arrives from an individual executive's personal checking account without explanation, the bank forex desk will freeze the funds demanding a formal third-party settlement authorization letter.
                        </p>
                    </div>
                </div>
            </section>

