                <h4 class="h6 fw-bold text-primary text-uppercase mb-2">Executive Summary</h4>
                <p class="mb-0 text-slate-700">
                    Under the Indian Goods and Services Tax (GST) regime, services are categorized using the <strong>Services Accounting Code (SAC)</strong> system governed by the Central Board of Indirect Taxes and Customs (CBIC). For information technology businesses and cross-border freelancers, the two most common classifications are <strong>SAC 998311</strong> (IT consulting and advisory services) and <strong>SAC 998312</strong> (IT design and development services). Choosing the wrong code can trigger audit notices during GSTR-9 annual reconciliation or cause disputes with tax authorities when validating zero-rated export statuses under a Letter of Undertaking (LUT).
                </p>
            </div>

            <!-- Section 1: Overview of SAC Codes -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">1. Understanding the SAC Code Hierarchy Under GST</h2>
                <p>
                    Similar to Harmonised System of Nomenclature (HSN) codes used for physical merchandise, Services Accounting Codes (SAC) are standardized 6-digit numerical identifiers based on the United Nations Central Product Classification (UN CPC) scheme.
                </p>
                <p>
                    All IT, computer, and professional services fall under <strong>Chapter 99</strong> of the GST Tariff:
                </p>
                <ul>
                    <li><strong>First 2 digits (99):</strong> Denotes that the supply is a Service (as opposed to physical goods).</li>
                    <li><strong>Middle 2 digits (83):</strong> Section heading for "Other professional, technical, and business services."</li>
                    <li><strong>Last 2 digits (11 or 12):</strong> Granular service specification—11 for consulting, 12 for software development.</li>
                </ul>
            </section>

            <!-- Section 2: Deep Dive into SAC 998311 -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">2. SAC Code 998311: Information Technology Consulting and Advisory</h2>
                <p>
                    Under the CBIC Explanatory Notes, <strong>SAC 998311</strong> covers advice, guidance, and operational assistance on information technology matters where the primary deliverable is <em>intellectual advisory, architecture assessment, or strategic direction</em> rather than delivering compilable production source code.
                </p>

                <div class="p-4 bg-white border rounded-3 mb-3">
                    <h3 class="h5 fw-bold text-dark mb-2">Eligible Deliverables Under 998311:</h3>
                    <ul class="text-slate-600 mb-0">
                        <li>IT systems and cybersecurity risk assessments.</li>
                        <li>Cloud migration architecture roadmaps and feasibility studies.</li>
                        <li>Technology stack evaluations and software vendor selection advisory.</li>
                        <li>Fractional Chief Technology Officer (CTO) or enterprise architect retainers.</li>
                        <li>Database optimization audits and performance tuning recommendations.</li>
                        <li>Business process re-engineering and digital transformation consulting.</li>
                    </ul>
                </div>
                <p class="small text-muted">
                    <em>Invoice Example:</em> "Advisory fee for enterprise cloud security audit and cloud migration roadmap for Q2 FY27."
                </p>
            </section>

            <!-- Section 3: Deep Dive into SAC 998312 -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">3. SAC Code 998312: Information Technology Design and Development</h2>
                <p>
                    In contrast, <strong>SAC 998312</strong> applies when your company or freelance practice is engaged in the <em>active engineering, creation, authoring, and deployment of software products, web platforms, mobile applications, or custom codebases</em>.
                </p>

                <div class="p-4 bg-white border rounded-3 mb-3">
                    <h3 class="h5 fw-bold text-dark mb-2">Eligible Deliverables Under 998312:</h3>
                    <ul class="text-slate-600 mb-0">
                        <li>Custom web application engineering (e.g. React, Vue, Next.js, Laravel).</li>
                        <li>Native or cross-platform mobile app development (iOS, Android, Flutter).</li>
                        <li>Custom backend API architecture, database schema creation, and server-side logic.</li>
                        <li>Bespoke software feature enhancements, modifications, and pull request implementations.</li>
                        <li>Integration of third-party payment gateways, CRM APIs, and webhook consumers.</li>
                        <li>Software prototyping, wireframe-to-code implementation, and continuous deployment scripting.</li>
                    </ul>
                </div>
                <p class="small text-muted">
                    <em>Invoice Example:</em> "Sprint 14 deliverable: Custom REST API development and Stripe subscription webhook integration."
                </p>
            </section>

