            <!-- Section 9: Income Tax TDS Implications -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">9. Income Tax TDS Classification: Section 194J vs Section 194C</h2>
                <p>
                    For domestic Indian B2B client billings, your SAC classification also impacts the rate of Tax Deducted at Source (TDS) under the Indian Income Tax Act, 1961:
                </p>
                <ul>
                    <li><strong>Section 194J (Fees for Technical Services - FTS):</strong> IT consulting under SAC 998311 is universally treated as Professional/Technical Services. In recent Finance Acts, TDS on technical services (FTS) is deducted at <strong>2%</strong> (reduced from 10%), while non-technical professional consulting can still attract 10%.</li>
                    <li><strong>Section 194C (Works / Service Contract):</strong> In cases where software development is billed as a milestone works contract without intellectual consulting, corporate clients sometimes argue for <strong>1% or 2%</strong> under Section 194C. Having clear SAC codes and SOW definitions ensures your Form 26AS and AIS accurately reflect technical services without audit mismatches.</li>
                </ul>
            </section>

