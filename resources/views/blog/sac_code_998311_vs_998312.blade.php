            <!-- Section 6: Mandatory Number of Digits on Invoices -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">6. Statutory Requirement: 4 Digits vs 6 Digits on Invoices</h2>
                <p>
                    Under Notification No. 78/2020-Central Tax, the government revised the mandatory number of HSN/SAC digits required on tax invoices based on aggregate annual turnover:
                </p>
                <div class="row g-3">
                    <div class="col-md-6">
                        <div class="p-3 bg-white border rounded-3 h-100">
                            <h4 class="h6 fw-bold text-dark mb-2">Turnover Up to ₹5 Crore</h4>
                            <p class="small text-slate-600 mb-0">
                                Taxpayers are legally required to quote a minimum of <strong>4 digits</strong> (e.g. <code>9983</code>) for B2B supplies. Quoting 4 digits for B2C supplies is optional.
                            </p>
                        </div>
                    </div>
                    <div class="col-md-6">
                        <div class="p-3 bg-white border rounded-3 h-100">
                            <h4 class="h6 fw-bold text-dark mb-2">Turnover Exceeding ₹5 Crore</h4>
                            <p class="small text-slate-600 mb-0">
                                Taxpayers must mandatorily declare the full <strong>6 digits</strong> (e.g. <code>998311</code> or <code>998312</code>) on all B2B tax invoices, export invoices, and credit notes.
                            </p>
                        </div>
                    </div>
                </div>
                <div class="callout-box bg-white border mt-3">
                    <p class="small mb-0 text-slate-700">
                        ⭐ <strong>Best Practice for Exporters:</strong> Even if your annual turnover is below ₹5 Crore, always quote the complete <strong>6-digit SAC code</strong> on export invoices. Overseas banks and payment aggregators (Stripe, PayPal, Wise) match the 6-digit SAC against your RBI Purpose Code (P0802/P1006) to issue clean FIRCs without manual delay.
                    </p>
                </div>
            </section>

            <!-- Section 7: Mixed & Composite Supply Scenarios -->
            <section class="mb-5">
                <h2 class="h3 fw-bold mb-3">7. Handling Mixed & Composite Supplies: Both Consulting & Coding</h2>
                <p>
                    Many digital agencies provide hybrid engagements—starting with architectural consulting (998311) and progressing to custom code development (998312). How should this be invoiced?
                </p>
                <p>
                    Under <strong>Section 8 of the CGST Act</strong>:
                </p>
                <ul>
                    <li><strong>Composite Supply:</strong> If the consulting and development are naturally bundled where development is the principal supply, the entire contract can be billed under SAC 998312.</li>
                    <li><strong>Itemized Billing (Recommended):</strong> The cleanest and most audit-proof approach is to list distinct line items on your invoice—one for "Architecture & Systems Design" under SAC 998311, and another for "Custom Frontend Engineering" under SAC 998312.</li>
                </ul>
            </section>

