                <h2 class="h3 fw-bold mb-3">2. Field-by-Field Breakdown: Page 2 (Details of Export Value)</h2>
                <p>
                    Page 2 lists the itemized invoice schedule and legal undertakings under Section 10(5), Chapter III of the Foreign Exchange Management Act, 1999.
                </p>

                <div class="step-card">
                    <h5 class="fw-bold text-dark mb-3">The Export Invoice Schedule (Table on Page 2)</h5>
                    <p class="fs-7 text-muted">
                        Every foreign invoice being regularized against the remittance must be declared across these 12 columns:
                    </p>
                    <ul class="fs-7 text-slate-700">
                        <li><strong>Service Recipient Name & Address:</strong> The full legal name and foreign address of your overseas customer.</li>
                        <li><strong>Country:</strong> The destination country (e.g. United States, United Arab Emirates, Australia).</li>
                        <li><strong>Invoice No. & Date:</strong> The exact invoice identifier (e.g. <code>INV-202610-0010</code>) and issue date.</li>
                        <li><strong>Currency & Gross Amount:</strong> Foreign currency code (AED, USD) and billed amount.</li>
                        <li><strong>Net Realisable Value:</strong> Billed amount minus any legitimate third-party deduction. Usually identical to Gross Amount.</li>
                        <li><strong>Description of Services:</strong> Specific IT service title (e.g. <em>Full-Stack Web Development, Cloud Infrastructure Maintenance</em>).</li>
                        <li><strong>SAC Code:</strong> Mandatory 6-digit Service Accounting Code: <strong>998314</strong> (IT Design & Development) or <strong>998315</strong> (Hosting & Infrastructure).</li>
                        <li><strong>Remarks:</strong> Crucial statutory clause: <em>"Export of Services under LUT No. AD100626002271U without payment of IGST"</em>.</li>
                    </ul>
                </div>

                <div class="step-card">
                    <h5 class="fw-bold text-dark mb-2">Mandatory Declarations on Page 2</h5>
                    <ul class="fs-7 text-slate-700 mb-0">
                        <li><strong>OFAC Declaration:</strong> You declare that neither the client nor the underlying jurisdiction is subject to US OFAC or international anti-money laundering sanctions.</li>
                        <li><strong>FEMA Declaration-cum-Undertaking:</strong> You declare that the transaction does not contravene any provisions of FEMA 1999 and that full value will be realized via authorized banking channels.</li>
                        <li><strong>Declaration 4:</strong> You certify as the service provider that the stated value represents the true contracted export value.</li>
                        <li><strong>Authorized Signature:</strong> Must be signed by the Proprietor, Partner, or Director whose signature card is registered with HDFC Bank, accompanied by the official company rubber stamp.</li>
                    </ul>
                </div>
