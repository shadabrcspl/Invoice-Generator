            <h2 class="h3 fw-bold mt-5 mb-3">Why Did HDFC Bank Send You This Circular?</h2>
            <p>
                If your business receives foreign currency wire transfers (USD, EUR, GBP, AED, AUD, etc.) into an HDFC Bank Current Account, you likely received an email titled: <em>"Implementation of Revised FEMA 23R Regulations with effect from October 01, 2026"</em>.
            </p>
            <p>
                Previously, many Indian service exporters operated on informal email disposal instructions or self-certified FIRC requests. Under the newly implemented <strong>Foreign Exchange Management (Export and Import of Goods and Services) Regulations, 2026 (FEMA 23R)</strong>, Authorized Dealer (AD) Category-I banks are held accountable by the RBI to record every export of services on the **EDPMS (Export Data Processing and Monitoring System)** portal.
            </p>
            <p>
                HDFC Bank standardized this compliance into a single 2-page document: the **"Export declaration form (EDF) cum Request letter"** (officially titled *Request letter for Export of Services & EDF Filing Cum Disposal Instructions for Credit*). Without this form, trade desks cannot liquidate your foreign exchange or issue your FIRC / e-BRC.
            </p>

